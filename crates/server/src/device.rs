//! A device approver that does not sign blind.
//!
//! It fetches the challenge, recomputes every hash from the action itself,
//! and signs the hash it computed, never one the server handed over. So the
//! person at the terminal approves what they read on their own screen, even
//! if the server (or something between them) lies about the hash.

use serde_json::{json, Value};
use std::time::Duration;
use twof_core::{canonical, Action, Binding};

/// A challenge as fetched and checked by the device.
pub struct Fetched {
    pub project_name: String,
    pub state: String,
    pub action: Action,
    pub binding: Binding,
}

fn agent() -> ureq::Agent {
    ureq::AgentBuilder::new()
        .timeout(Duration::from_secs(15))
        .redirects(0)
        .build()
}

fn explain(error: ureq::Error) -> String {
    match error {
        ureq::Error::Status(code, response) => {
            let body = response.into_string().unwrap_or_default();
            let message = canonical::parse_strict(&body)
                .ok()
                .and_then(|v| v["error"]["message"].as_str().map(str::to_owned))
                .unwrap_or(body);
            format!("the server answered {code}: {message}")
        }
        other => format!("could not reach the server: {other}"),
    }
}

/// Challenge ids are generated by the server as `ch_` plus 32 hex digits.
/// Anything else is refused before it is put into a URL.
pub fn valid_challenge_id(id: &str) -> bool {
    id.strip_prefix("ch_")
        .is_some_and(|hex| hex.len() == 32 && hex.bytes().all(|b| b.is_ascii_hexdigit()))
}

/// Checks that what the server sent is self consistent: the binding is for
/// this challenge and its action hash is the hash of the action shown.
pub fn check(challenge: &str, view: &Value) -> Result<Fetched, String> {
    let field = |name: &str| {
        view.get(name)
            .cloned()
            .ok_or(format!("the answer has no {name}"))
    };
    let action = Action::from_value(field("action")?).map_err(|e| e.to_string())?;
    let binding: Binding =
        serde_json::from_value(field("binding")?).map_err(|e| format!("binding: {e}"))?;
    let action_hash = action.hash_hex().map_err(|e| e.to_string())?;
    if binding.v != 1 || binding.challenge != challenge || binding.action_hash != action_hash {
        return Err(
            "the server sent a binding that does not match the action shown; \
                    nothing was signed"
                .into(),
        );
    }
    Ok(Fetched {
        project_name: view["project_name"].as_str().unwrap_or("").to_owned(),
        state: view["state"].as_str().unwrap_or("").to_owned(),
        action,
        binding,
    })
}

pub fn fetch(server_url: &str, challenge: &str) -> Result<Fetched, String> {
    if !valid_challenge_id(challenge) {
        return Err("that is not a challenge id".into());
    }
    let url = format!(
        "{}/v1/approvals/{challenge}",
        server_url.trim_end_matches('/')
    );
    let body = agent()
        .get(&url)
        .call()
        .map_err(explain)?
        .into_string()
        .map_err(|e| e.to_string())?;
    let view = canonical::parse_strict(&body).map_err(|e| e.to_string())?;
    check(challenge, &view)
}

/// Sends the decision. Returns the challenge state afterwards.
pub fn submit(
    server_url: &str,
    challenge: &str,
    credential: &str,
    signature: &str,
    reject: bool,
) -> Result<String, String> {
    if !valid_challenge_id(challenge) {
        return Err("that is not a challenge id".into());
    }
    let url = format!(
        "{}/v1/challenges/{challenge}/approvals",
        server_url.trim_end_matches('/')
    );
    let body = json!({ "credential": credential, "signature": signature,
                       "decision": if reject { "reject" } else { "approve" } });
    let answer = agent()
        .post(&url)
        .set("Content-Type", "application/json")
        .send_string(&body.to_string())
        .map_err(explain)?
        .into_string()
        .map_err(|e| e.to_string())?;
    let value = canonical::parse_strict(&answer).map_err(|e| e.to_string())?;
    Ok(value["state"].as_str().unwrap_or("unknown").to_owned())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn view(action: Value, challenge: &str) -> Value {
        let parsed = Action::from_value(action.clone()).unwrap();
        let binding = Binding::new("pj", challenge, &parsed.hash_hex().unwrap(), 2_000_000_000);
        json!({ "project_name": "Exchange", "state": "pending", "action": action, "binding": binding })
    }

    #[test]
    fn a_consistent_answer_is_accepted() {
        let id = "ch_0123456789abcdef0123456789abcdef";
        let fetched = check(id, &view(json!({ "type": "withdraw", "amount": "5" }), id)).unwrap();
        assert_eq!(fetched.action.amount.as_deref(), Some("5"));
        assert_eq!(fetched.project_name, "Exchange");
    }

    #[test]
    fn a_lying_server_is_caught_before_anything_is_signed() {
        let id = "ch_0123456789abcdef0123456789abcdef";
        // Shows a harmless action, but the binding is for a dangerous one.
        let mut lie = view(json!({ "type": "withdraw", "amount": "5" }), id);
        let evil = view(json!({ "type": "withdraw", "amount": "5000000" }), id);
        lie["binding"] = evil["binding"].clone();
        assert!(check(id, &lie).is_err());
        // The binding belongs to another challenge.
        let other = view(
            json!({ "type": "withdraw", "amount": "5" }),
            "ch_ffffffffffffffffffffffffffffffff",
        );
        assert!(check(id, &other).is_err());
        // Missing or malformed parts.
        assert!(check(id, &json!({})).is_err());
        assert!(check(
            id,
            &json!({ "action": { "type": "x", "amount": 5 }, "binding": {} })
        )
        .is_err());
    }

    #[test]
    fn challenge_ids_are_checked_before_use() {
        assert!(valid_challenge_id("ch_0123456789abcdef0123456789abcdef"));
        for bad in [
            "",
            "ch_",
            "ch_123",
            "ch_0123456789abcdef0123456789abcdeg",
            "../admin",
            "ch_0123456789abcdef0123456789abcdef/x",
        ] {
            assert!(!valid_challenge_id(bad), "{bad}");
        }
        assert!(fetch("http://127.0.0.1:1", "../../etc").is_err());
    }
}
